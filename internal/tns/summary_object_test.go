// TestSummaryArrayDMLError is sijms/go-ora#698: before TTC 7 the errors of a
// batch were read as three empty DLCs, so a batch that failed on 11g waited
// for bytes that never came.
func TestSummaryArrayDMLError(t *testing.T) {
	// TTC 7 adds the return code and the row count after the arrays
	at := bytes.Index(arrayDMLError, []byte{0x21, 'O', 'R', 'A'})
	ttc7 := append(append(append([]byte{}, arrayDMLError[:at]...), 0x02, 0x5f, 0x3d, 0x01, 0x01), arrayDMLError[at:]...)
	for _, test := range []struct {
		ttc uint8
		in  []byte
	}{
		{6, arrayDMLError},
		{7, ttc7},
	} {
		s := NewSessionWithInputBufferForDebug(test.in)
		s.HasEOSCapability, s.HasFSAPCapability, s.TTCVersion = true, true, test.ttc
		sum, err := NewSummary(s)
		if err != nil {
			t.Fatalf("TTC %d: %v", test.ttc, err)
		}
		if sum.RetCode != 1 || !strings.HasPrefix(string(sum.ErrorMessage), "ORA-00001:") {
			t.Errorf("TTC %d: got %d %q, want ORA-00001", test.ttc, sum.RetCode, sum.ErrorMessage)
		}
		if len(sum.bindErrors) != 1 || sum.bindErrors[0].rowOffset != 1 {
			t.Errorf("TTC %d: got the bind errors %+v, want one at row 1", test.ttc, sum.bindErrors)
		}
		if n := s.inBuffer.Len(); n != 0 {
			t.Errorf("TTC %d: %d bytes left", test.ttc, n)
		}
	}
}
